/**
 * 后期课堂 (0.19.0): data types of the mixing course. Lessons are plain data
 * (src/mixing/lessons.ts); the lesson page renders them with the shared mix
 * engine (audio/sing/mixChain), the same one the 跟唱 post-production desk uses.
 */
import type { MixSettings } from '@/songs/singTypes'

export type MixUnitId = 'basics' | 'eq' | 'dynamics' | 'space' | 'vocal' | 'color' | 'master'

export interface MixUnit {
  id: MixUnitId
  title: string
  summary: string
}

/** Deep partial of the mix settings: what a demo or task changes on top of the neutral base. */
export type MixPatch = {
  [K in keyof MixSettings]?: { [P in keyof MixSettings[K]]?: MixSettings[K][P] extends Array<unknown> ? MixSettings[K][P] : MixSettings[K][P] extends object ? Partial<MixSettings[K][P]> : MixSettings[K][P] }
}

/**
 * Lesson material. 'voice' is the student's own 20-second recording (or a
 * 跟唱 take); the others are generated by the site (drums, bass, piano; no
 * copyrighted music). 'full' = voice + band.
 */
export type Material = 'voice' | 'band' | 'drums' | 'bass' | 'piano' | 'full'

/** A problem mixed into the material on purpose, for the student to fix. */
export type Problem = 'rumble' | 'hiss' | 'sibilance' | 'boomy' | 'harsh' | 'uneven' | 'quiet' | 'clipping' | 'muddyBacking' | 'dull'

/**
 * Settings the lesson shows as controls: dotted paths into MixSettings, e.g.
 * 'vocal.lowCut.freq', 'vocal.comp.ratio', 'vocal.eq.bands.2.gainDb',
 * 'master.gainDb'. Booleans become switches. The registry with labels and
 * ranges is src/mixing/controls.ts.
 */
export type ControlPath = string

/** One "A vs B" listening comparison, played at matched loudness. */
export interface DemoSpec {
  material: Material
  problems?: Problem[]
  a: MixPatch
  b: MixPatch
  aLabel: string
  bLabel: string
  /** What to listen for (one sentence). */
  listenFor: string
  /** Turn off loudness matching (for lessons about loudness itself). */
  noLevelMatch?: boolean
}

/** A condition on a setting. */
export interface SettingCheck {
  path: ControlPath
  min?: number
  max?: number
  /** For switches. */
  equals?: boolean | string
}

/** A condition measured on the rendered result. */
export type MeasureCheck =
  | { kind: 'lufs'; target: number; tolerance: number }
  | { kind: 'truePeak'; max: number }
  | { kind: 'gainReduction'; min: number; max: number }
  | { kind: 'lowEnergyCut'; minDb: number }
  | { kind: 'sibilanceCut'; minDb: number }
  | { kind: 'phraseSpread'; maxDb: number }

export interface TaskSpec {
  material: Material
  problems?: Problem[]
  /** Starting settings (on top of the neutral base). */
  start: MixPatch
  controls: ControlPath[]
  /** What to do, in one or two sentences. */
  goal: string
  checks: SettingCheck[]
  measures?: MeasureCheck[]
  /** Shown when it passes. */
  success: string
  /** Shown after a failed check (general advice; the failing condition is shown too). */
  hint: string
}

export type EarDrillKind =
  | 'eqFreq'
  | 'eqBoostCut'
  | 'lowCut'
  | 'compAmount'
  | 'reverbSize'
  | 'delayTime'
  | 'pan'
  | 'distortion'
  | 'loudness'
  | 'width'

export interface MixCourseLesson {
  id: string
  unit: MixUnitId
  title: string
  minutes: number
  /** Explanation, plain text paragraphs (Chinese), each under ~120 characters. */
  body: string[]
  /** 2–4 short take-aways. */
  keyPoints: string[]
  /** Optional diagram shown above the text. */
  figure?: 'freqMap' | 'eqShapes' | 'compCurve' | 'envelope' | 'reverbTail' | 'panField' | 'loudnessMeter' | 'signalChain' | 'saturationCurve' | 'msMatrix'
  demo?: DemoSpec
  task?: TaskSpec
  /** Ear drill to practise after the lesson. */
  drill?: EarDrillKind
  /** The 跟唱 desk panel this lesson explains (for the "去学这一课" link). */
  deskModule?: string
}
