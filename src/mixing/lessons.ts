import type { EqBand } from '@/songs/singTypes'
import type { MixCourseLesson, MixUnit, MixUnitId } from './types'

/** The neutral four-band layout (all flat). */
const FLAT: EqBand[] = [
  { type: 'lowshelf', freq: 120, gainDb: 0, q: 0.7 },
  { type: 'peaking', freq: 300, gainDb: 0, q: 1 },
  { type: 'peaking', freq: 3000, gainDb: 0, q: 1 },
  { type: 'highshelf', freq: 10000, gainDb: 0, q: 0.7 },
]

/** The flat layout with some bands changed. */
function bands(changes: Partial<Record<0 | 1 | 2 | 3, Partial<EqBand>>> = {}): EqBand[] {
  return FLAT.map((b, i) => ({ ...b, ...(changes[i as 0 | 1 | 2 | 3] ?? {}) }))
}

