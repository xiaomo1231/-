const mel = (notes: Array<[number, number, number, string?]>): ScoreNote[] =>
  notes.map(([start, beats, midi, lyric]) => ({ start, beats, midi, ...(lyric ? { lyric } : {}) }))

/** One chord per bar. */
const bars = (romans: RomanId[]): ChordSlot[] => romans.map((roman, i) => ({ start: i * 4, beats: 4, roman }))

